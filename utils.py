def send_report_email(
    doctor_email,
    patient_name,
    age,
    gender,
    risk,
    bpm,
    probability,
    pdf_path
):
    msg = EmailMessage()
    msg["From"] = EMAIL_ADDRESS
    msg["To"] = doctor_email
    msg["Subject"] = f"ECG Report – {patient_name}"

    msg.set_content(f"""
AI ECG ARRHYTHMIA REPORT

Patient Name: {patient_name}
Age: {age}
Gender: {gender}

Risk Level: {risk}
Heart Rate: {bpm} BPM
Probability: {probability:.2%}

This report is generated by the AI Cardiac Diagnostic System.
""")

    with open(pdf_path, "rb") as f:
        msg.add_attachment(
            f.read(),
            maintype="application",
            subtype="pdf",
            filename="ECG_Report.pdf"
        )

    with smtplib.SMTP(SMTP_SERVER, SMTP_PORT) as server:
        server.starttls()
        server.login(EMAIL_ADDRESS, EMAIL_PASSWORD)
        server.send_message(msg)
